/**
 * Clear learning records, e.g. after testing. The records are the daily notes in the vault, so this
 * deletes notes. It also removes what older versions of neko kept: the record tables in the
 * database and the Index.md / Grammar/ notes it used to generate.
 *
 *   npm run reset-records                                show what would be deleted; changes nothing
 *   npm run reset-records -- --yes                       delete every daily note
 *   npm run reset-records -- --before 2026-11-03 --yes   delete only daily notes from before that day
 *   add --pet                                            also reset ねこ's hunger, happiness and streak
 *
 * Stop neko first (sudo systemctl stop neko). Notes/ (Hermes's notes) and the rest of the vault
 * are not touched. The database is backed up to data/neko-backup-<time>.db before it is changed.
 */
import { existsSync, readdirSync, rmSync } from "node:fs";
import path from "node:path";
import { config } from "../src/config.ts";
import { db } from "../src/db.ts";

const args = process.argv.slice(2);
const apply = args.includes("--yes");
const pet = args.includes("--pet");
const beforeArg = args.indexOf("--before");
const before = beforeArg >= 0 ? args[beforeArg + 1] : null;
if (beforeArg >= 0 && !/^\d{4}-\d{2}-\d{2}$/.test(before ?? "")) {
  console.error("--before needs a date like 2026-11-03");
  process.exit(1);
}
if (!config.vaultDir) {
  console.error("No vault configured (NEKO_VAULT_DIR).");
  process.exit(1);
}

const vault = config.vaultDir;
const dailyDir = path.join(vault, "Daily");
const daily = existsSync(dailyDir)
  ? readdirSync(dailyDir).filter((f) => /^\d{4}-\d{2}-\d{2}\.md$/.test(f) && (!before || f.slice(0, 10) < before))
  : [];
// generated by older versions of neko; nothing writes them now
const oldNotes = ["Index.md", "Grammar"].filter((p) => existsSync(path.join(vault, p)));
const tables = (db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all() as { name: string }[]).map((t) => t.name);
const oldTables = ["review_attempts", "challenge_attempts", "mistakes", "turns", "listening", "asks"].filter((t) => tables.includes(t));

console.log(`vault: ${vault}`);
console.log(`  Daily notes ${before ? `from before ${before}` : "(all)"}: ${daily.length}${daily.length ? ` (${daily[0].slice(0, 10)} … ${daily.at(-1)!.slice(0, 10)})` : ""}`);
if (oldNotes.length) console.log(`  old generated notes: ${oldNotes.join(", ")}`);
console.log(`database: ${path.join(config.dataDir, "neko.db")}`);
if (oldTables.length) console.log(`  old record tables (no longer used): ${oldTables.join(", ")}`);
if (pet) console.log("  ねこ's hunger, happiness and practice history (streak) reset to a fresh start");
console.log("Not touched: Notes/ and anything else in the vault, translation challenge sentences.");

if (!apply) {
  console.log("\nNothing changed. Add --yes to do it.");
  process.exit(0);
}

if (oldTables.length || pet) {
  const backup = path.join(config.dataDir, `neko-backup-${new Date().toISOString().replace(/[:.]/g, "-")}.db`);
  db.exec(`VACUUM INTO '${backup.replace(/'/g, "''")}'`);
  console.log(`\ndatabase backed up to ${backup}`);
  for (const t of oldTables) db.exec(`DROP TABLE ${t}`);
  if (pet) {
    db.exec("DELETE FROM practice");
    db.prepare("UPDATE pet SET hunger = 30, happiness = 70, updated_at = ? WHERE id = 1").run(Date.now());
  }
}
for (const f of daily) rmSync(path.join(dailyDir, f));
for (const p of oldNotes) rmSync(path.join(vault, p), { recursive: true, force: true });
console.log(`deleted ${daily.length} daily notes${oldNotes.length ? ` and ${oldNotes.join(", ")}` : ""}`);
console.log("Done. Start neko again: sudo systemctl start neko");
